import assert from 'node:assert/strict';
import {appendAiReading, mergeJournalRecords, migrateJournalPayload, normalizeHistoryRecords, readingVersions} from './storage.mjs';
import {journalStatus, normalizeJournal, validReviewDate} from './journal.mjs';
import {fetchLibraryJson} from './library-loader.mjs';

const base={id:'record',question:'如何推进求职？',lines:Array.from({length:6},()=>({value:7,changes:[{},{},{}]})),originalIndex:0,changedIndex:0,createdAt:'2026-10-01T00:00:00.000Z',updatedAt:'2026-10-01T00:00:00.000Z',note:'旧札记'};
const ai=(text,date)=>({text,generatedAt:date,language:'zh-CN'});
const first=ai('首次的判断','2026-10-01T00:00:00.000Z');
const legacy=migrateJournalPayload([{...base,aiReading:first}]).records[0];
assert.equal(legacy.note,'旧札记');assert.equal(readingVersions(legacy).length,1);
const updated=appendAiReading(legacy,ai('第二版判断','2026-10-02T00:00:00.000Z'));
assert.equal(updated.aiReadings[0].text,first.text);assert.equal(updated.aiReadings[1].text,'第二版判断');
assert.equal(migrateJournalPayload(JSON.parse(JSON.stringify({records:[updated]}))).records[0].aiReadings.length,2);
assert.equal(normalizeHistoryRecords(Array.from({length:130},(_,i)=>({...base,id:String(i)}))).length,130,'old records must not disappear after the hundredth reading');
assert.equal(mergeJournalRecords(Array.from({length:130},(_,i)=>({...base,id:String(i)})),[]).length,130);
assert.equal(validReviewDate('2026-02-30'),false);assert.equal(validReviewDate('2028-02-29'),true);
assert.equal(journalStatus({journal:{reviewDate:'2026-10-28'}},new Date(2026,9,28,0,1)),'due');
assert.equal(journalStatus({journal:{reviewDate:'2026-10-29'}},new Date(2026,9,28,23,59)),'open');
const entry=(id,kind='progress')=>({id,kind,createdAt:'2026-10-28T01:00:00.000Z',facts:'收到面试反馈',actions:'修改作品',assessment:'仍待观察',nextStep:'继续投递'});
const a={...updated,updatedAt:'2026-10-28T02:00:00.000Z',journal:{reviewDate:'2026-10-28',entries:[entry('a')]}};
const b={...legacy,updatedAt:'2026-10-28T03:00:00.000Z',journal:{reviewDate:'2026-10-29',status:'reviewed',entries:[entry('b','review')]}};
const merged=mergeJournalRecords([a],[b])[0];
assert.deepEqual(merged.journal.entries.map(e=>e.id),['a','b']);assert.equal(merged.aiReadings.length,2);
assert.equal(journalStatus(merged),'reviewed');assert.equal(merged.journal.reviewDate,'2026-10-29');
assert.deepEqual(mergeJournalRecords([merged],[a])[0].journal.entries.map(e=>e.id),['a','b']);
assert.equal(normalizeJournal({status:'reviewed',entries:[{id:'x',kind:'review',createdAt:'bad'}]}).status,'open');
assert.equal(normalizeJournal({entries:[entry('a'),entry('a')]}).entries.length,1);
assert.deepEqual(await fetchLibraryJson('x',{fetchImpl:async()=>Response.json({ok:1})}),{ok:1});
await assert.rejects(fetchLibraryJson('x',{fetchImpl:async()=>new Response('',{status:503})}),/HTTP 503/);
await assert.rejects(fetchLibraryJson('x',{timeoutMs:10,fetchImpl:()=>new Promise(()=>{})}),/timeout/);
await assert.rejects(fetchLibraryJson('x',{timeoutMs:10,fetchImpl:async()=>({ok:true,json:()=>new Promise(()=>{})})}),/timeout/);
console.log('Journal: legacy migration, permanent AI versions, 130 records, local dates, multi-device merge, malformed data and bounded loading passed.');
